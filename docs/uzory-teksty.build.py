# ---------- оформление ----------
def shade(cell, hexcol):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), hexcol)
    tcPr.append(sh)


def new_doc(title, sub):
    d = Document()
    s = d.sections[0]
    s.orientation = WD_ORIENT.LANDSCAPE
    s.page_width, s.page_height = s.page_height, s.page_width
    for m in ('left_margin', 'right_margin', 'top_margin', 'bottom_margin'):
        setattr(s, m, Cm(1.6))
    st = d.styles['Normal']; st.font.name = 'Arial'; st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn('w:eastAsia'), 'Arial')
    d.add_heading(title, 0)
    p = d.add_paragraph(sub); p.runs[0].italic = True
    return d


def para(d, text, bold=False, size=None, color=None):
    p = d.add_paragraph()
    r = p.add_run(text); r.bold = bold
    if size: r.font.size = Pt(size)
    if color: r.font.color.rgb = RGBColor.from_string(color)
    return p


def bullets(d, items):
    for t in items:
        p = d.add_paragraph(style='List Bullet')
        m = re.match(r'^\*\*(.+?)\*\*(.*)$', t, re.S)
        if m:
            p.add_run(m.group(1)).bold = True; p.add_run(m.group(2))
        else:
            p.add_run(t)


def table(d, rows):
    """rows: (где, текст сейчас, комментарий) — комментарий '' = всё хорошо."""
    t = d.add_table(rows=1, cols=3)
    t.style = 'Table Grid'
    w = (Cm(5.2), Cm(10.5), Cm(10.8))
    for i, h in enumerate(('Где и что', 'Текст сейчас', 'Комментарий и вариант')):
        c = t.rows[0].cells[i]; c.text = ''; r = c.paragraphs[0].add_run(h); r.bold = True; shade(c, 'E8E2F4'); c.width = w[i]
    for where, now, com in rows:
        cs = t.add_row().cells
        for i in range(3): cs[i].width = w[i]
        cs[0].text = where
        for r in cs[0].paragraphs[0].runs: r.font.size = Pt(9); r.font.color.rgb = RGBColor(0x55, 0x55, 0x66)
        cs[1].text = now if now else '(пусто)'
        cs[2].text = ''
        p = cs[2].paragraphs[0]
        if com:
            # «→ вариант» — отдельной строкой, жирным
            parts = com.split('\n→ ')
            p.add_run(parts[0])
            for v in parts[1:]:
                p.add_run('\n→ ').bold = True
                rr = p.add_run(v); rr.bold = True; rr.font.color.rgb = RGBColor(0x2E, 0x5E, 0x3A)
            shade(cs[2], 'FFF6E0')
        else:
            rr = p.add_run('хорошо'); rr.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
    d.add_paragraph()


def sec(d, title, note=None):
    d.add_heading(title, 1)
    if note: para(d, note, color='666666')


