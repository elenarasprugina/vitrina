  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) lines(n, text);
    return n;
  }
  // Enter в панели — новая строка
  function lines(n, s) {
    String(s).split('\n').forEach(function (l, i) { if (i) n.appendChild(document.createElement('br')); inline(n, l); });
    return n;
  }
  // **жирный**
  function inline(n, s) {
    String(s).split(/\*\*/).forEach(function (part, i) {
      if (!part) return;
      if (i % 2) { var b = document.createElement('strong'); b.textContent = part; n.appendChild(b); }
      else n.appendChild(document.createTextNode(part));
    });
  }
  function val(h, k) { var v = h && h[k]; return typeof v === 'string' && v.trim() ? v : DEF[k]; }
  function listOf(h, k) { return (h && Array.isArray(h[k]) ? h[k] : DEF[k]).filter(function (x) { return x && x.visible !== false; }); }
  function same(a, b) { function n(s) { return String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]+/g, ''); } return n(a) === n(b); }

  // Текст раздела → абзацы и списки
  function body(text) {
    var box = el('div', 'hw-text');
    String(text || '').replace(/\r/g, '').split(/\n[ \t]*\n/).forEach(function (chunk) {
      var ls = chunk.split('\n').filter(function (l) { return l.trim(); });
      if (!ls.length) return;
      var ul = ls.every(function (l) { return /^\s*[-•–]\s+/.test(l); }), ol = ls.every(function (l) { return /^\s*\d+[.)]\s+/.test(l); });
      if (ul || ol) {
        var list = el(ol ? 'ol' : 'ul', 'hw-list');
        ls.forEach(function (l) { list.appendChild(el('li', null, l.replace(ol ? /^\s*\d+[.)]\s+/ : /^\s*[-•–]\s+/, ''))); });
        box.appendChild(list);
      } else box.appendChild(el('p', null, ls.join('\n')));
    });
    return box;
  }

  function render(app, h, j, base) {
    h = h || {};
    app.replaceChildren();
    var page = el('main', 'hw-page');
    var nav = el('nav', 'hw-nav');
    var back = el('a', 'hw-back', j ? val(h, 'back') : val(h, 'home'));
    back.href = j ? base + (j.path || 'routes/' + j.id + '/') : base;
    nav.appendChild(back);
    page.appendChild(nav);
    page.appendChild(el('p', 'hw-kicker', j && j.title ? '13 MIRRORS · ' + j.title : '13 MIRRORS'));
    page.appendChild(el('h1', 'hw-title', val(h, 'title')));
    document.title = '13 MIRRORS · ' + val(h, 'title').replace(/\n/g, ' ');
    listOf(h, 'sections').forEach(function (s) {
      if (!String(s.title || '').trim() && !String(s.text || '').trim()) return;
      var sec = el('section', 'hw-sec');
      if (String(s.title || '').trim()) sec.appendChild(el('h2', 'hw-h2', s.title));
      sec.appendChild(body(s.text));
      page.appendChild(sec);
    });
    // Вопросы этой волны — первыми; общий вопрос с тем же текстом не повторяем
    var own = j && Array.isArray(j.howFaq) ? j.howFaq.filter(function (x) { return x && x.visible !== false && String(x.q || '').trim(); }) : [];
    var faq = own.concat(listOf(h, 'faq').filter(function (x) { return String(x.q || '').trim() && !own.some(function (o) { return same(o.q, x.q); }); }));
    if (faq.length) {
      var fs = el('section', 'hw-sec hw-faq');
      fs.appendChild(el('h2', 'hw-h2', val(h, 'faqTitle')));
      faq.forEach(function (x) {
        var d = el('details', 'hw-q');
        d.appendChild(el('summary', null, x.q));
        if (String(x.a || '').trim()) d.appendChild(body(x.a));
        fs.appendChild(d);
      });
      page.appendChild(fs);
    }
    var foot = el('nav', 'hw-nav hw-nav--end'), back2 = back.cloneNode(true);
    foot.appendChild(back2);
    page.appendChild(foot);
    app.appendChild(page);
  }

  function getJSON(url, n) {
    n = n || 0;
    return fetch(url, { cache: n ? 'reload' : 'no-cache' }).then(function (r) { if (!r.ok) throw new Error(url); return r.json(); })
      .catch(function (e) { if (n >= 2) throw e; return new Promise(function (ok) { setTimeout(ok, [0, 1500][n]); }).then(function () { return getJSON(url, n + 1); }); });
  }
  function q(name) { var m = new RegExp('[?&]' + name + '=([^&#]*)').exec(location.search); return m ? decodeURIComponent(m[1].replace(/\+/g, ' ')) : null; }

  function boot() {
    var app = document.getElementById('hw');
    if (!app) return;
    var base = app.getAttribute('data-base') || '../', rid = q('r');
    if (q('preview') === '1') {
      window.addEventListener('message', function (e) {
        if (e.origin !== location.origin || !e.data || !e.data.m13how) return;
        render(app, e.data.m13how, e.data.journey || null, base);
      });
      try { window.parent.postMessage({ m13howReady: true }, location.origin); } catch (e) {}
      return;
    }
    Promise.all([
      getJSON(base + 'data/settings.json').catch(function () { return {}; }),
      rid ? getJSON(base + 'data/journeys.json').catch(function () { return null; }) : null
    ]).then(function (r) {
      var j = rid && r[1] ? ((r[1].items || []).filter(function (x) { return x && x.id === rid && x.visible !== false; })[0] || null) : null;
      render(app, (r[0] || {}).howTo, j, base);
    });
  }

  window.M13H = { DEF: DEF, boot: boot };
